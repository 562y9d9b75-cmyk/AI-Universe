from .db import *
from .appearance import DEFAULT_EMPLOYEES, default_appearance
from .employee_defaults import role_defaults
ROSTER=[(p['name'],p['role'],p['department']) for p in DEFAULT_EMPLOYEES]
def seed(s,org):
    deps={}
    for n in dict.fromkeys(x[2] for x in ROSTER):
        d=Department(organization_id=org,name=n,description=n+'部门');s.add(d);s.flush();deps[n]=d.id
    ceo=None
    for i,(n,r,d) in enumerate(ROSTER):
        a=Agent(organization_id=org,name=n,role=r,department_id=deps[d],manager_id=ceo,**role_defaults(r),permissions=['documents','analysis'],appearance=default_appearance(DEFAULT_EMPLOYEES[i]['portrait_id'],i))
        s.add(a);s.flush()
        if i==0:ceo=a.id
        for skill in a.skills:s.add(AgentSkill(organization_id=org,agent_id=a.id,name=skill))
        for p in a.permissions:s.add(AgentPermission(organization_id=org,agent_id=a.id,name=p))
        s.add(EmployeeAnimation(organization_id=org,agent_id=a.id,state='idle'))
    s.add(OfficeAsset(organization_id=org,name='总部楼层 / 原创模块',uri='/assets/headquarters-v2.glb',license='CC0-1.0; generated by scripts/build_assets.py'))
